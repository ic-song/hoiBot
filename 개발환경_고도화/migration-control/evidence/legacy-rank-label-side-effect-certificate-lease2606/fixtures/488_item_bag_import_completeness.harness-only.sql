-- WBS777: bind one explicit legacy BAG_CONTAINER witness to each imported player bag.
CREATE TABLE player_item_bag_import_completeness_projections (
  player_item_bag_import_completeness_projection_id CHAR(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  player_id CHAR(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  object_domain_import_run_id CHAR(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  common_staging_record_id CHAR(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  projection_version VARCHAR(50) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  profile_semantic_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  import_contract_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  source_locator_sha256 CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  source_payload_fingerprint CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  expected_source_key_count INT UNSIGNED NOT NULL,
  projected_stack_count INT UNSIGNED NOT NULL,
  quarantined_source_key_count INT UNSIGNED NOT NULL,
  ignored_source_key_count INT UNSIGNED NOT NULL,
  stack_set_fingerprint CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  item_ledger_entry_count BIGINT UNSIGNED NOT NULL,
  item_ledger_set_fingerprint CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  completeness_fingerprint CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  revision BIGINT UNSIGNED NOT NULL,
  active_flag BOOLEAN NOT NULL DEFAULT TRUE,
  active_player_guard TINYINT UNSIGNED GENERATED ALWAYS AS (CASE WHEN active_flag THEN 1 ELSE NULL END) STORED,
  INSERT_USER VARCHAR(100) NOT NULL,
  INSERT_TIME CHAR(19) NOT NULL,
  UPDATE_USER VARCHAR(100) NOT NULL,
  UPDATE_TIME CHAR(19) NOT NULL,
  PRIMARY KEY(player_item_bag_import_completeness_projection_id),
  UNIQUE KEY uq_player_item_bag_import_completeness_active(player_id,active_player_guard),
  UNIQUE KEY uq_player_item_bag_import_completeness_run_player(object_domain_import_run_id,player_id),
  UNIQUE KEY uq_player_item_bag_import_completeness_run_witness(object_domain_import_run_id,common_staging_record_id),
  UNIQUE KEY uq_player_item_bag_import_completeness_revision(player_id,revision),
  CONSTRAINT fk_player_item_bag_import_completeness_player FOREIGN KEY(player_id) REFERENCES canonical_players(player_id) ON DELETE RESTRICT,
  CONSTRAINT fk_player_item_bag_import_completeness_run FOREIGN KEY(object_domain_import_run_id) REFERENCES data_migration_object_domain_import_runs(object_domain_import_run_id) ON DELETE RESTRICT,
  CONSTRAINT fk_player_item_bag_import_completeness_witness FOREIGN KEY(common_staging_record_id) REFERENCES data_migration_common_staging_records(common_staging_record_id) ON DELETE RESTRICT,
  CONSTRAINT chk_player_item_bag_import_completeness_version CHECK(projection_version='OBJECT_DOMAIN_IMPORT_RELEVANT_V3'),
  CONSTRAINT chk_player_item_bag_import_completeness_counts CHECK(projected_stack_count=expected_source_key_count AND quarantined_source_key_count=0 AND ignored_source_key_count=0),
  CONSTRAINT chk_player_item_bag_import_completeness_revision CHECK(revision>=1),
  CONSTRAINT chk_player_item_bag_import_completeness_profile_hash CHECK(profile_semantic_sha256 REGEXP '^[0-9a-f]{64}$'),
  CONSTRAINT chk_player_item_bag_import_completeness_contract_hash CHECK(import_contract_sha256 REGEXP '^[0-9a-f]{64}$'),
  CONSTRAINT chk_player_item_bag_import_completeness_source_locator CHECK(source_locator_sha256 REGEXP '^[0-9a-f]{64}$'),
  CONSTRAINT chk_player_item_bag_import_completeness_source_payload CHECK(source_payload_fingerprint REGEXP '^[0-9a-f]{64}$'),
  CONSTRAINT chk_player_item_bag_import_completeness_stack_set CHECK(stack_set_fingerprint REGEXP '^[0-9a-f]{64}$'),
  CONSTRAINT chk_player_item_bag_import_completeness_ledger_set CHECK(item_ledger_set_fingerprint REGEXP '^[0-9a-f]{64}$'),
  CONSTRAINT chk_player_item_bag_import_completeness_fingerprint CHECK(completeness_fingerprint REGEXP '^[0-9a-f]{64}$'),
  CONSTRAINT chk_player_item_bag_import_completeness_insert_time CHECK(INSERT_TIME REGEXP '^[0-9]{4}-(0[1-9]|1[0-2])-(0[1-9]|[12][0-9]|3[01]) ([01][0-9]|2[0-3]):[0-5][0-9]:[0-5][0-9]$'),
  CONSTRAINT chk_player_item_bag_import_completeness_update_time CHECK(UPDATE_TIME REGEXP '^[0-9]{4}-(0[1-9]|1[0-2])-(0[1-9]|[12][0-9]|3[01]) ([01][0-9]|2[0-3]):[0-5][0-9]:[0-5][0-9]$')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
