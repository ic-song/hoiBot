  CONSTRAINT chk_legacy_rank_label_certificate_guild CHECK(guild_pointer_state IN ('NONE','VALID','STALE_GUILD','MEMBER_MISMATCH')),
  CONSTRAINT chk_legacy_rank_label_certificate_decision CHECK(side_effect_decision IN ('NO_WRITE','WOULD_DELETE','UNMAPPED')),
  CONSTRAINT chk_legacy_rank_label_certificate_source_hash CHECK(source_player_key_sha256 REGEXP '^[0-9a-f]{64}$'),
  CONSTRAINT chk_legacy_rank_label_certificate_pointer_hash CHECK(guild_pointer_fingerprint REGEXP '^[0-9a-f]{64}$'),
  CONSTRAINT chk_legacy_rank_label_certificate_membership_hash CHECK(membership_evidence_fingerprint REGEXP '^[0-9a-f]{64}$'),
  CONSTRAINT chk_legacy_rank_label_certificate_fingerprint CHECK(certificate_fingerprint REGEXP '^[0-9a-f]{64}$'),
  CONSTRAINT chk_legacy_rank_label_certificate_insert_time CHECK(INSERT_TIME REGEXP '^[0-9]{4}-(0[1-9]|1[0-2])-(0[1-9]|[12][0-9]|3[01]) ([01][0-9]|2[0-3]):[0-5][0-9]:[0-5][0-9]$'),
  CONSTRAINT chk_legacy_rank_label_certificate_update_time CHECK(UPDATE_TIME REGEXP '^[0-9]{4}-(0[1-9]|1[0-2])-(0[1-9]|[12][0-9]|3[01]) ([01][0-9]|2[0-3]):[0-5][0-9]:[0-5][0-9]$')
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
